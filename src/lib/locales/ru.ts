/** "1 матч", "3 матча", "5 матчей". */
const p = (n: number, one: string, few: string, many: string) => {
  const d = n % 10;
  const h = n % 100;
  return `${n} ${d === 1 && h !== 11 ? one : d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many}`;
};
const matches = (n: number) => p(n, 'матч', 'матча', 'матчей');

