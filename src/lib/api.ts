import { invoke } from '@tauri-apps/api/core';
import type { CpuAssist, Devices, DiskInfo, Job, OutplayedScan, Project, Recording, Settings, Snapshot, Status, UpdateState } from './types';

export const api = {
  bootstrap: () => invoke<{ settings: Settings; mediaUrl: string; version: string; status: Status; systemLanguage: 'en' | 'zh-CN'; update: UpdateState; updatedFrom: string | null }>('bootstrap'),
  saveSettings: (settings: Settings) => invoke<void>('save_settings', { settings }),
  systemFonts: () => invoke<string[]>('system_fonts'),
  readThemeFile: (path: string) => invoke<string>('read_theme_file', { path }),
  writeThemeFile: (path: string, contents: string) => invoke<void>('write_theme_file', { path, contents }),
  listDevices: () => invoke<Devices>('list_devices'),
  getLibrary: () => invoke<Snapshot>('get_library'),
  getStatus: () => invoke<Status>('get_status'),
  setFavorite: (id: string, favorite: boolean) => invoke<Recording>('set_favorite', { id, favorite }),
  renameRecording: (id: string, title: string) => invoke<Recording>('rename_recording', { id, title }),
  renameSession: (id: string, title: string) => invoke<void>('rename_session', { id, title }),
  deleteRecordings: (ids: string[]) => invoke<void>('delete_recordings', { ids }),
  restoreRecordings: (ids: string[]) => invoke<void>('restore_recordings', { ids }),
  purgeRecordings: (ids: string[]) => invoke<void>('purge_recordings', { ids }),
  emptyRecentlyDeleted: () => invoke<void>('empty_recently_deleted'),
  revealRecording: (id: string) => invoke<void>('reveal_recording', { id }),
  openMediaFolder: () => invoke<void>('open_media_folder'),
  diskInfo: () => invoke<DiskInfo>('disk_info'),
  quickTrim: (id: string, start: number, end: number, title: string) => invoke<Recording>('quick_trim', { id, start, end, title }),
  supercut: (id: string, kinds: string[], before: number, after: number) => invoke<string>('supercut', { id, kinds, before, after }),
  cancelJob: (id: string) => invoke<void>('cancel_job', { id }),
  getSprite: (id: string) => invoke<string | null>('get_sprite', { id }),
  toggleScreenRecorder: () => invoke<void>('toggle_screen_recorder'),
  ensureArt: (key: string) => invoke<boolean>('ensure_art', { key }),
  championNamesZh: () => invoke<Record<string, string>>('champion_names_zh'),
  checkUpdate: () => invoke<UpdateState>('check_update'),
  installUpdate: () => invoke<void>('install_update'),
  listProjects: () => invoke<Project[]>('list_projects'),
  getProject: (id: string) => invoke<Project>('get_project', { id }),
  createProject: (clips: { recordingId: string; start: number; end: number }[]) => invoke<Project>('create_project', { clips }),
  saveProject: (project: Project) => invoke<Project>('save_project', { project }),
  deleteProject: (id: string) => invoke<void>('delete_project', { id }),
  exportProject: (id: string, codec: string) => invoke<string>('export_project', { id, codec }),
  changeMediaFolder: (path: string, moveMedia: boolean) => invoke<string>('change_media_folder', { path, moveMedia }),
  createBackup: (dest: string) => invoke<string>('create_backup', { dest }),
  quitApp: () => invoke<void>('quit_app'),
  scanOutplayed: (folder?: string) => invoke<OutplayedScan>('scan_outplayed', { folder: folder ?? null }),
  importOutplayed: (folder: string, includeDeleted = false, deleteSources = false) => invoke<string>('import_outplayed', { folder, includeDeleted, deleteSources }),
  importLibrary: (folder: string) => invoke<string>('import_library', { folder }),
  listJobs: () => invoke<Job[]>('list_jobs'),
  pauseJob: (id: string, paused: boolean) => invoke<void>('pause_job', { id, paused }),
  importCpuAssist: () => invoke<CpuAssist>('import_cpu_assist'),
  setImportCpuAssist: (on: boolean) => invoke<CpuAssist>('set_import_cpu_assist', { on }),
  deleteSessions: (ids: string[]) => invoke<number>('delete_sessions', { ids }),
};
